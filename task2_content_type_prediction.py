import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, f1_score, confusion_matrix, classification_report

df = pd.read_csv("Dataset.csv")
df = df.replace("Not Given", "")
df = df.drop_duplicates(subset=["title", "type", "release_year"]).reset_index(drop=True)
print(df.shape)
print(df["type"].value_counts(normalize=True).round(3))

df["is_tv_show"] = (df["type"] == "TV Show").astype(int)      # the answer we predict: 1 = TV Show, 0 = Movie
df["year_added"] = pd.to_datetime(df["date_added"], errors="coerce").dt.year
df["year_added"] = df["year_added"].fillna(df["year_added"].median())
df["num_directors"] = df["director"].apply(lambda s: len([d for d in s.split(",") if d.strip()]))

# duration is split into two numbers; we keep these for an experiment later
df["duration_min"] = df["duration"].str.extract(r"(\d+) min")[0].astype(float).fillna(0)
df["duration_seasons"] = df["duration"].str.extract(r"(\d+) Season")[0].astype(float).fillna(0)

df[["title", "type", "is_tv_show", "year_added", "num_directors", "duration_min", "duration_seasons"]].head()

train_df, test_df = train_test_split(df, test_size=0.2, stratify=df["is_tv_show"], random_state=42)
y_train, y_test = train_df["is_tv_show"], test_df["is_tv_show"]
print(len(train_df), len(test_df))

genre_vec = CountVectorizer(tokenizer=lambda s: [g.strip() for g in s.split(",")],
                            lowercase=False, token_pattern=None)

def build_encoder(num_cols, cat_cols, use_genres):
    parts = [("num", "passthrough", num_cols)]                          # numbers are used as they are
    if cat_cols:
        parts.append(("cat", OneHotEncoder(handle_unknown="ignore"), cat_cols))   # each category becomes its own 0/1 column
    if use_genres:
        parts.append(("genres", genre_vec, "listed_in"))                # each genre becomes its own 0/1 column
    return ColumnTransformer(parts)

models = {
    "Logistic Regression": LogisticRegression(max_iter=2000, class_weight="balanced"),
    "Decision Tree": DecisionTreeClassifier(random_state=42, class_weight="balanced"),
    "Random Forest": RandomForestClassifier(n_estimators=200, random_state=42, class_weight="balanced", n_jobs=-1),
}

def run_experiment(name, num_cols, cat_cols, use_genres):
    rows = []
    for model_name, model in models.items():
        pipe = Pipeline([("encode", build_encoder(num_cols, cat_cols, use_genres)), ("model", model)])
        pipe.fit(train_df, y_train)             # learn from the training data
        pred = pipe.predict(test_df)            # predict the unseen test data
        rows.append({"features": name, "model": model_name,
                     "accuracy": accuracy_score(y_test, pred),
                     "f1_tv_show": f1_score(y_test, pred)})
    return pd.DataFrame(rows).round(3)

base_num = ["release_year", "year_added", "num_directors"]
base_cat = ["rating", "country"]

print("Always-guess-Movie accuracy:", round(1 - y_test.mean(), 3))
results_C = run_experiment("C: no duration, no genres", base_num, base_cat, False)
results_C

import matplotlib.pyplot as plt

ax = results_C.plot.bar(x="model", y=["accuracy", "f1_tv_show"], figsize=(8, 5), rot=0)
ax.set_title("Model comparison (honest features: no duration, no genres)")
ax.set_ylabel("Score")
ax.set_ylim(0, 1)
ax.axhline(0.697, color="red", linestyle="--", label="Always guess Movie (0.697)")
for c in ax.containers:
    ax.bar_label(c, fmt="%.3f", fontsize=8)
ax.legend(loc="lower right")
plt.tight_layout()
plt.show()

results_B = run_experiment("B: + genres", base_num, base_cat, True)
results_A = run_experiment("A: + genres + duration", base_num + ["duration_min", "duration_seasons"], base_cat, True)
pd.concat([results_A, results_B, results_C], ignore_index=True)

all_results = pd.concat([results_A, results_B, results_C], ignore_index=True)
table = all_results.pivot(index="features", columns="model", values="accuracy")

ax = table.plot.bar(figsize=(9, 5), rot=0)
ax.set_title("Accuracy by feature set: leakage makes scores look perfect")
ax.set_ylabel("Accuracy")
ax.set_ylim(0.8, 1.01)
plt.tight_layout()
plt.show()

pipe = Pipeline([("encode", build_encoder(base_num, base_cat, False)),
                 ("model", models["Random Forest"])]).fit(train_df, y_train)
pred = pipe.predict(test_df)
print(confusion_matrix(y_test, pred))
print(classification_report(y_test, pred, target_names=["Movie", "TV Show"]))